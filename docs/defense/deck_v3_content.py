def check():
    banned = ["GitHub", "github", "仓库", "提交记录", "commit", "PR ", "克隆", "clone",
              "CI ", "门禁", "视频"]
    problems = []
    total_chars = 0
    total_secs = 0
    for p in SPEC:
        n = len(p["note"])
        total_chars += n
        total_secs += p["secs"]
        est = n / RATE
        if est > p["secs"] * 1.10:
            problems.append(f"P{p['no']:02d} 口播 {n} 字 ≈{est:.0f}s，超出预算 {p['secs']}s（>110%）")
        if est < p["secs"] * 0.80:
            problems.append(f"P{p['no']:02d} 口播 {n} 字 ≈{est:.0f}s，预算 {p['secs']}s 太空（<80%）")
        blob = " ".join([p["title"], p["kicker"], p["lead"], str(p["data"]), p["note"]])
        for b in banned:
            if b in blob:
                problems.append(f"P{p['no']:02d} 出现禁词 {b!r}")
    return problems, total_chars, total_secs


